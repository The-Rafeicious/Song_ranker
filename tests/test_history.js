/* Selection, stale lookup protection, keyboard access and explicit form scope. */
const {JSDOM}=require('jsdom'),fs=require('node:fs'),assert=require('node:assert/strict');
(async()=>{
 const dom=new JSDOM(`<form id="archive-filters"><label>Mode<select name="mode" id="archive-mode"><option value="all">All modes</option></select></label><label>Record type<select name="entity" id="archive-kind"><option value="songs">Songs</option><option value="tags">Tags</option></select></label><div class="archive-lookup"><input id="archive-search"><input id="archive-target"><button type="button" id="archive-clear">Clear</button><div id="archive-suggestions" hidden></div><p id="archive-selection"></p></div><p id="archive-error"></p></form>`,{url:'https://example.test/history',runScripts:'outside-only'}),w=dom.window;
 let calls=[],pending=[];
 w.fetch=(url)=>{calls.push(url);return new Promise(resolve=>pending.push(resolve));};
 for(const name of ['ui','gameplay','history'])w.eval(fs.readFileSync('static/js/'+name+'.js','utf8'));
 w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
 const $=id=>w.document.getElementById(id), wait=()=>new Promise(r=>setTimeout(r,300));
 const input=text=>{$('archive-search').value=text;$('archive-search').dispatchEvent(new w.Event('input',{bubbles:true}));};
 assert.equal($('archive-kind').name,'entity');
 assert.ok($('archive-kind').hidden);
 input('one');await wait();
 input('two');await wait();
 pending[0]({ok:true,json:async()=>({items:[{id:1,name:'Old'}]})});await wait();
 assert.equal($('archive-suggestions').textContent,'');
 pending[1]({ok:true,json:async()=>({items:[{id:2,name:'<Chosen>',artists:[{name:'Artist'}],album:{name:'Album'},cover:'/cover'}]})});await wait();
 assert.equal($('archive-suggestions').hidden,false);
 assert.equal($('archive-suggestions').querySelector('strong').textContent,'<Chosen>');
 $('archive-search').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true,cancelable:true}));
 assert.equal(w.document.activeElement,$('archive-suggestions').querySelector('button'));
 w.document.activeElement.click();
 assert.equal($('archive-target').value,'2');
 assert.equal($('archive-selection').textContent,'Selected: <Chosen>');
 assert.equal($('archive-suggestions').hidden,true);
 input('new');
 const event=new w.Event('submit',{cancelable:true});$('archive-filters').dispatchEvent(event);
 assert.equal(event.defaultPrevented,true);
 $('archive-clear').click();
 assert.equal($('archive-target').value,'');
 assert.equal($('archive-search').value,'');
 input('tag');await wait();
 $('archive-kind').value='tags';$('archive-kind').dispatchEvent(new w.Event('change',{bubbles:true}));
 pending[2]({ok:true,json:async()=>({items:[{id:3,name:'Stale song'}]})});await wait();
 assert.equal($('archive-suggestions').hidden,true);
 assert.equal($('archive-target').value,'');
 assert.ok(calls[0].includes('lookup=songs'));
 dom.window.close();
 console.log('History lookup, shared selectors, keyboard, stale response and form checks passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
