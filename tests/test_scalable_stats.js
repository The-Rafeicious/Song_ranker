const {JSDOM} = require('jsdom');
const fs = require('node:fs'), assert = require('node:assert/strict');
(async () => {
  const dom = new JSDOM('<style>dd{font:900 36px Arial}</style><main id="main"><dl class="mode-stats-metrics"><div data-width="220"><dt>Tracks voted</dt><dd>1300</dd></div><div data-width="50"><dt>Elo rating</dt><dd>1234.56</dd></div><div data-width="50"><dt>Best score</dt><dd>12345</dd></div></dl></main>', {runScripts:'outside-only'});
  const w = dom.window;
  Object.defineProperty(w.HTMLElement.prototype,'clientWidth',{get(){return Number(this.dataset.width||0)}});
  w.HTMLCanvasElement.prototype.getContext=()=>({font:'',measureText(text){return {width:text.length*(parseFloat(this.font.match(/[\d.]+px/)?.[0])||36)*.6}}});
  const flush=()=>new Promise(resolve=>w.setTimeout(resolve,10));
  w.eval(fs.readFileSync('static/js/ui.js', 'utf8'));
  w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
  const counts = w.document.querySelectorAll('dd'), slot=counts[0].parentElement;
  assert.equal(counts[0].textContent, '1300','full count remains when its slot has room');
  assert.equal(counts[0].hasAttribute('aria-label'),false);
  slot.dataset.width='50';w.dispatchEvent(new w.Event('resize'));await flush();
  assert.equal(counts[0].textContent, '1.3k');
  assert.equal(counts[0].getAttribute('aria-label'), '1,300');
  assert.equal(counts[1].textContent, '1234.56','ratings preserve precision even in tight slots');
  assert.equal(counts[2].textContent, '12345','scores never become abbreviated counts');
  slot.dataset.width='220';w.dispatchEvent(new w.Event('resize'));await flush();
  assert.equal(counts[0].textContent,'1300','wider slots restore the exact value');
  assert.equal(counts[0].hasAttribute('aria-label'),false);
  counts[0].textContent = '23';await flush();
  assert.equal(counts[0].textContent, '23');
  assert.equal(counts[0].hasAttribute('aria-label'), false);
  slot.dataset.width='50';counts[0].textContent = '1234567';await flush();
  assert.equal(counts[0].textContent, '1.2m');
  assert.equal(counts[0].title, '1,234,567');
  assert.equal(w.SongRankerUI.countText(null), '—');
  dom.window.close();
  console.log('Scalable summaries: exact values first, measured fit, resize restoration, protected score precision and refreshed counts passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
